import matplotlib.pyplot as plt
import matplotlib.patches as patches

# Plagiarism Report Mockup (Page 35)
def create_plagiarism_page():
    fig, ax = plt.subplots(figsize=(8, 10))
    ax.axis('off')
    
    # Outer frame
    ax.add_patch(patches.Rectangle((0.05, 0.05), 0.9, 0.9, ec="#888", fc="#fff", lw=1))
    
    # Header
    ax.text(0.5, 0.88, "DrillBit", color='#0066cc', fontsize=20, fontweight='bold', ha='center')
    ax.text(0.5, 0.84, "The Report is Generated by DrillBit Plagiarism Detection Software", color='#444', fontsize=9, ha='center')
    ax.plot([0.1, 0.9], [0.81, 0.81], color='#ccc', lw=1)
    
    # Submission details
    details = [
        ("Author Name:", "Kachare Vaibhav, Temgire Devdatta, Shriyan Dheeraj, Kaushik Serin"),
        ("Title:", "SecureFlowAI: Data Leakage Prevention for Financial Workflows"),
        ("Paper/Submission ID:", "894120"),
        ("Submitted By:", "student@siesgst.ac.in"),
        ("Submission Date:", "2026-10-15 14:22:10"),
        ("Total Pages:", "37"),
        ("Document Type:", "Project Report")
    ]
    ax.text(0.12, 0.77, "Submission Information", color='#004080', fontsize=11, fontweight='bold')
    for idx, (k, v) in enumerate(details):
        y = 0.73 - idx * 0.03
        ax.text(0.12, y, k, color='#333', fontsize=9, fontweight='bold')
        ax.text(0.36, y, v, color='#555', fontsize=9)
        
    ax.plot([0.1, 0.9], [0.50, 0.50], color='#ccc', lw=1)
    ax.text(0.12, 0.46, "Result Information", color='#004080', fontsize=11, fontweight='bold')
    ax.text(0.12, 0.41, "Similarity Score: 9%", color='#008800', fontsize=13, fontweight='bold')
    ax.text(0.12, 0.37, "AI Generated Text: 11%", color='#cc6600', fontsize=11, fontweight='bold')

    # Pie Chart in the middle
    ax_pie = fig.add_axes([0.35, 0.18, 0.3, 0.22])
    ax_pie.pie([11, 89], labels=['AI Text\n11.0%', 'Human Text\n89.0%'], colors=['#3399ff', '#f0f0f0'],
               wedgeprops={'edgecolor': '#888', 'linewidth': 1}, startangle=90)

    # Disclaimer
    ax.text(0.5, 0.08, "Disclaimer: The content detection system employed here is powered by academic verification tools.\nIt is designed to assist in identifying and moderating content for institutional originality compliance.", 
            color='#777', fontsize=7.5, ha='center', style='italic')

    plt.tight_layout()
    plt.savefig("report_assets/fig_plagiarism.png", dpi=200)
    plt.close()
    print("Created fig_plagiarism.png")

